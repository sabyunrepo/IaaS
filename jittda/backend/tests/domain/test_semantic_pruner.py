"""
Semantic Pruner 도메인 테스트 — TDD

AST 노이즈 제거 규칙:
  각 코드 라인을 import / comment / config / generated / logic 으로 분류하고
  PureContribution 모델로 집계한다.
"""
import pytest

from domain.identity.semantic_pruner import PruningCategory, classify_line, prune_contribution


# ---------------------------------------------------------------------------
# classify_line — parametrize
# ---------------------------------------------------------------------------


class TestClassifyLine:
    @pytest.mark.parametrize(
        "line, expected",
        [
            # IMPORT
            ("import os", PruningCategory.IMPORT),
            ("import sys", PruningCategory.IMPORT),
            ("from pathlib import Path", PruningCategory.IMPORT),
            ("from . import utils", PruningCategory.IMPORT),
            ("from ..domain import models", PruningCategory.IMPORT),
            # COMMENT
            ("# This is a comment", PruningCategory.COMMENT),
            ("// javascript comment", PruningCategory.COMMENT),
            ("/* block comment */", PruningCategory.COMMENT),
            ("*/", PruningCategory.COMMENT),
            ("* @param foo", PruningCategory.COMMENT),
            ('"""docstring"""', PruningCategory.COMMENT),
            ("'''docstring'''", PruningCategory.COMMENT),
            # CONFIG
            ("DEBUG = True", PruningCategory.CONFIG),
            ("DATABASE_URL = 'postgres://...'", PruningCategory.CONFIG),
            ("MAX_RETRIES = 3", PruningCategory.CONFIG),
            ("LOG_LEVEL = 'INFO'", PruningCategory.CONFIG),
            # GENERATED (takes priority over COMMENT)
            ("# Generated by protobuf", PruningCategory.GENERATED),
            ("# auto-generated", PruningCategory.GENERATED),
            ("# DO NOT EDIT", PruningCategory.GENERATED),
            ("// autogenerated file", PruningCategory.GENERATED),
            ("# This file is auto-generated. Do not edit.", PruningCategory.GENERATED),
            # LOGIC
            ("def calculate(x, y):", PruningCategory.LOGIC),
            ("    return x + y", PruningCategory.LOGIC),
            ("class UserService:", PruningCategory.LOGIC),
            ("    if x > 0:", PruningCategory.LOGIC),
            ("result = compute()", PruningCategory.LOGIC),
            ("", PruningCategory.LOGIC),  # empty line → LOGIC (not noise)
            ("    ", PruningCategory.LOGIC),  # whitespace-only → LOGIC
        ],
    )
    def test_classify_line(self, line: str, expected: PruningCategory):
        assert classify_line(line) == expected


# ---------------------------------------------------------------------------
# classify_line — edge cases
# ---------------------------------------------------------------------------


class TestClassifyLineEdgeCases:
    def test_import_with_leading_whitespace_is_not_import(self):
        """들여쓰기된 import는 LOGIC (함수 내부 지역 import)."""
        # 설계 결정: 줄 시작 strip 후 패턴 적용 — 어느 쪽이든 명확히 테스트
        # 현 구현은 strip 후 패턴 매칭이므로 들여쓰기 import도 IMPORT로 분류된다.
        result = classify_line("    import os")
        assert result == PruningCategory.IMPORT

    def test_lowercase_config_is_logic(self):
        """소문자 변수 할당은 CONFIG가 아닌 LOGIC."""
        assert classify_line("result = compute()") == PruningCategory.LOGIC

    def test_partial_caps_is_logic(self):
        """일부만 대문자인 변수는 CONFIG가 아닌 LOGIC."""
        assert classify_line("MyClass = type('MyClass', (), {})") == PruningCategory.LOGIC


